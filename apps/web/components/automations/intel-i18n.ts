const DICTS: Record<Locale, Dict> = { he: he as Dict, en, ar };

export type IntelKey = Key;
export type IntelT = (key: IntelKey | (string & {}), params?: Record<string, string | number>) => string;

export function intelDict(locale: Locale): Dict {
  return DICTS[locale] ?? DICTS.he;
}

/** Translator for the intelligence layer. Unknown keys fall back to Hebrew, then to the key itself. */
export function intelT(locale: Locale): IntelT {
  const d = DICTS[locale] ?? DICTS.he;
  return (key, params) => {
    const raw = (d as Record<string, string>)[key] ?? (DICTS.he as Record<string, string>)[key] ?? key;
    return params ? raw.replace(/\{(\w+)\}/g, (_, n: string) => (n in params ? String(params[n]) : `{${n}}`)) : raw;
  };
}

