#!/usr/bin/env node
// Regenerates supabase/migrations/20261015000003_permissions_seed.sql from
// packages/shared/src/permissions.ts (the single source of truth).
// Usage: node scripts/setup/generate-permissions-sql.mjs
// Requires Node >= 22.18 (native TypeScript type stripping).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const { ORG_ROLES, PERMISSIONS, ROLE_PERMISSIONS } = await import(
  path.join(root, "packages/shared/src/permissions.ts")
);

const ranks = {
  agency_owner: 100, owner: 90, admin: 80, manager: 60, marketing: 40,
  sales: 40, support: 40, analyst: 30, client: 10, read_only: 10,
};

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
let sql = `-- ============================================================================
-- SUPER CODER CLOUD — 0003 Permission catalogue + role mapping
-- GENERATED by scripts/setup/generate-permissions-sql.mjs — do not edit by hand.
-- Source of truth: packages/shared/src/permissions.ts
-- ============================================================================

insert into public.permissions (key) values
${PERMISSIONS.map((p) => `  (${q(p)})`).join(",\n")}
on conflict (key) do nothing;

insert into public.roles (key, rank) values
${ORG_ROLES.map((r) => `  (${q(r)}, ${ranks[r]})`).join(",\n")}
on conflict (key) do update set rank = excluded.rank;

delete from public.role_permissions;
insert into public.role_permissions (role, permission) values
`;
const rows = [];
for (const role of ORG_ROLES) for (const p of ROLE_PERMISSIONS[role]) rows.push(`  (${q(role)}, ${q(p)})`);
sql += rows.join(",\n") + ";\n";

const out = path.join(root, "supabase/migrations/20261015000003_permissions_seed.sql");
writeFileSync(out, sql);
console.log(`wrote ${rows.length} role-permission rows → ${path.relative(root, out)}`);
